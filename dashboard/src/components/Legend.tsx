import { useId, useMemo, useState } from "react";
import { useApp } from "../state/AppState";
import { LAYERS } from "../data/types";
import { globeColors, MISSING_OUTLINE } from "../viz/globeColors";
import { changeLayer } from "../viz/layerValue";
import { fmt } from "../viz/format";

export function Legend({ year, yearLast }: { year: number; yearLast: boolean }) {
  const { data, layer, dark } = useApp();
  const [visible, setVisible] = useState(true);
  const keyId = useId();

  const colors = useMemo(() => data ? globeColors(data, year, layer, dark) : null,
    [data, year, layer, dark]);
  if (!colors) return null;
  const { domain, bound, fill, stroke } = colors;
  const meta = LAYERS[layer];
  const changeMeta = LAYERS[changeLayer(layer)];
  const fillMeaning: Partial<Record<typeof layer, string>> = {
    clean_share: "Darker blue = a larger share of electricity comes from renewables and nuclear. This shows a cleaner electricity mix, not necessarily a larger market or faster growth.",
    clean_gen: "Darker blue = more electricity generated from renewables and nuclear. This highlights larger clean-energy markets; check the growth charts for momentum.",
    coal_share: "Darker red = a larger share of electricity comes from coal. This shows greater reliance on coal, not necessarily more coal production.",
    coal_gen: "Darker red = more electricity generated by burning coal. This highlights larger markets for coal-fired power; it does not measure coal mining.",
    coal_prod: "Darker red = more coal mined. This highlights larger coal-producing countries; production may serve domestic users or exports.",
    coal_tes: "Darker red = more coal in the country’s energy supply. This highlights coal use across the economy, including uses beyond electricity.",
  };

  return (
    <div>
      <button className="iconbtn" aria-expanded={visible} aria-controls={keyId}
        onClick={() => setVisible(value => !value)} style={{ marginBottom: visible ? 8 : 0 }}>
        {visible ? "Hide key" : "Show key"}
      </button>
      <div id={keyId} hidden={!visible}>
      <div className="ltitle">{meta.label} {meta.unit && `(${meta.unit})`}</div>
      <div className="lsub">{meta.source}</div>
      {fill ? (
        <>
          <div className="legend-bar" style={{ background: fill.cssGradient }} />
          <div className="legend-scale">
            <span>{fmt(domain![0])}</span>
            <span>{fmt((domain![0] + domain![1]) / 2)}</span>
            <span>{fmt(domain![1])}</span>
          </div>
        </>
      ) : (
        <div className="lsub">No values reported for {year}</div>
      )}

      <p className="lsub" aria-label="What the country fill tells us" style={{ marginTop: 8 }}>
        {fillMeaning[layer] ?? `Darker fill = a higher ${meta.label.toLowerCase()} value.`} Lighter shades mean lower values.
      </p>

      {colors.changeCount > 0 && (
        <>
          <div className="lsub" style={{ marginTop: 8 }}>
            {changeMeta.label} growth, border color (% vs {year - 1}) · {changeMeta.source}
          </div>
          <div className="legend-bar" style={{ background: stroke.cssGradient }} />
          <div className="legend-scale">
            <span>−{fmt(bound)}%</span>
            <span>0</span>
            <span>+{fmt(bound)}%</span>
          </div>
        </>
      )}
      {colors.changeCount > 0 && <div className="lsub">{colors.declineLabel} = decrease · {colors.growthLabel.toLowerCase()} = increase · neutral = little or no change.</div>}
      {colors.changeCount > 0 && <p className="lsub" aria-label="What the country outline tells us">
        {colors.growthLabel} border: {changeMeta.label.toLowerCase()} grew. {colors.declineLabel} border: it fell.
        Stronger color means a larger percentage change, not a larger market.
        {layer === "clean_share" || layer === "coal_share" ? " Borders show generation growth, not percentage-point changes in share." : ""}
      </p>}
      <div className="legend-nodata">
        <span style={{ width: 18, borderTop: `3px solid ${MISSING_OUTLINE}`, display: "inline-block" }} />
        <span>Gray border = growth unavailable; both years and a positive previous-year value are required.</span>
      </div>
      {yearLast && (
        <div className="lsub" style={{ marginTop: 8 }}>
          2025 coverage differs by source. Borders use the selected industry’s data in both years; no missing year is treated as zero.
        </div>
      )}

      <div className="legend-nodata">
        <span className="sw" />
        <span>Fill: not reported / no data — never rendered as 0</span>
      </div>
      <div className="lsub">Scale follows this year/layer; use values for comparisons across years.</div>

      </div>
    </div>
  );
}
